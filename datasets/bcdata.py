"""
Dataset implementation for the BCData Ki67 dataset.

This module mirrors the original project structure while exposing a
``BCDataDataset`` class that understands how to read the histology
images, parse the positive and negative cell annotation files, and
produce both localization and count heatmaps.  The heatmaps are
generated by callable transforms provided at construction time.

The implementation is intentionally minimal and does not depend on
any global state from the surrounding codebase.  It accepts an
optional ``transform`` callable which operates on the raw image
tensor.  This allows you to plug in colour jitter or normalisation
without having to modify the dataset itself.  Spatial transforms
(flips, rotations, crops) are not applied here because they would
require corresponding updates to the annotation coordinates.

Example
-------

>>> from pathlib import Path
>>> from datasets.bcdata import BCDataDataset
>>> ds = BCDataDataset(Path('/path/to/data'), 'train', loc_gen, dens_gen, transform=None)
>>> img, loc_hm, dens_hm, pos_pts, neg_pts = ds[0]

"""

from typing import Callable, List, Tuple, Any
from pathlib import Path
from torch.utils.data import Dataset
import torch
import numpy as np
import cv2
import h5py


class BCDataDataset(Dataset):
    """
    Parses images and annotations for the BCData Ki67 dataset.

    Parameters
    ----------
    root : Path
        Root directory where ``images`` and ``annotations`` live.
    split : str
        One of ``train``, ``validation`` or ``test``.  Determines
        which subdirectory is read.
    target_loc_transform : Callable
        A callable that accepts a tensor of shape ``(N, 2)`` and
        returns a single‑channel heatmap tensor of shape
        ``(1, H_out, W_out)``.  This is typically an instance of
        ``PointsToLocalizationHeatmap`` from ``datasets.transforms``.
    target_count_transform : Callable
        A callable with the same signature as
        ``target_loc_transform`` but which generates a heatmap where
        the sum of the pixel values corresponds to the cell count.
    transform : Callable | None, optional
        A callable applied to the image tensor (shape ``(3, H, W)``)
        before any other processing.  Useful for colour jitter and
        normalisation.  Avoid spatial transforms here, since the
        annotation coordinates will not be updated.
    """

    SUPPORTED_SPLITS = {"train", "validation", "test"}

    def __init__(
        self,
        root: Path,
        split: str,
        target_loc_transform: Callable,
        target_count_transform: Callable,
        transform: Callable | None = None,
        joint_transform: Callable[[torch.Tensor, torch.Tensor, torch.Tensor], tuple[torch.Tensor, torch.Tensor, torch.Tensor]] | None = None,
    ) -> None:
        self.root = Path(root)
        self.split = split
        self.transform = transform
        # ``joint_transform`` is applied to the image and point annotations
        # simultaneously (e.g. random rotations).  It must return a tuple
        # ``(img_tensor, pos_pts, neg_pts)``.  If ``None``, no joint
        # transformation is applied.
        self.joint_transform = joint_transform
        self.target_loc_transform = target_loc_transform
        self.target_count_transform = target_count_transform

        if split not in self.SUPPORTED_SPLITS:
            raise ValueError(f"Unknown split '{split}'. Must be one of {self.SUPPORTED_SPLITS}")

        self.image_dir = self.root / "images" / str(split)
        pos_ann_dir = self.root / "annotations" / str(split) / "positive"
        neg_ann_dir = self.root / "annotations" / str(split) / "negative"

        if not self.image_dir.exists():
            raise FileNotFoundError(self.image_dir)
        if not pos_ann_dir.exists():
            raise FileNotFoundError(pos_ann_dir)
        if not neg_ann_dir.exists():
            raise FileNotFoundError(neg_ann_dir)

        self.samples: List[Tuple[Path, Path, Path]] = self._build_index()

    def _build_index(self) -> List[Tuple[Path, Path, Path]]:
        image_paths = sorted(self.image_dir.glob("*.png"))
        if not image_paths:
            raise RuntimeError(f"No images found in {self.image_dir}")

        samples: List[Tuple[Path, Path, Path]] = []

        for img_path in image_paths:
            stem = img_path.stem

            pos_ann_path = self.root / "annotations" / self.split / "positive" / (stem + ".h5")
            neg_ann_path = self.root / "annotations" / self.split / "negative" / (stem + ".h5")

            if not pos_ann_path.exists() or not neg_ann_path.exists():
                raise FileNotFoundError(f'Missing annotation: "{pos_ann_path}", "{neg_ann_path}"')

            samples.append((img_path, pos_ann_path, neg_ann_path))

        return samples

    def __len__(self) -> int:
        return len(self.samples)

    def _load_points(self, ann_path: Path) -> torch.Tensor:
        with h5py.File(ann_path, "r") as f:
            dset = f["coordinates"]
            assert isinstance(dset, h5py.Dataset)
            coords = torch.from_numpy(dset[:]).to(torch.float32)  # shape (N, 2)
        return coords

    def __getitem__(self, idx: int) -> Any:
        """
        Load one sample and convert annotations to two‑channel heatmaps.

        Returns
        -------
        tuple
            ``(img, loc_heatmap, count_heatmap, pos_pts, neg_pts)`` where:
            - ``img`` has shape ``(3, 640, 640)`` and is normalised to the
              range ``[0, 1]`` or whatever the provided ``transform``
              yields.
            - ``loc_heatmap`` has shape ``(2, H_out, W_out)``.
            - ``count_heatmap`` has shape ``(2, H_out, W_out)``.
            - ``pos_pts`` is a tensor of shape ``(N_pos, 2)``.
            - ``neg_pts`` is a tensor of shape ``(N_neg, 2)``.
        """
        img_path, pos_ann_path, neg_ann_path = self.samples[idx]

        img = cv2.imread(str(img_path))
        if img is None:
            raise RuntimeError(f"Failed to read image at {img_path}")
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0
        img_tensor = torch.from_numpy(img).permute(2, 0, 1).contiguous()

        # Load point annotations as tensors (shape (N, 2))
        pos_pts: torch.Tensor = self._load_points(pos_ann_path)
        neg_pts: torch.Tensor = self._load_points(neg_ann_path)

        # Apply joint transform (e.g. random rotation) before any image‑only
        # transformation.  This transform must return a new image tensor and
        # updated point coordinates.  If no joint transform is provided,
        # ``img_tensor``, ``pos_pts`` and ``neg_pts`` remain unchanged.
        if self.joint_transform is not None:
            img_tensor, pos_pts, neg_pts = self.joint_transform(img_tensor, pos_pts, neg_pts)

        # Apply image‑only transform if provided.  Use a copy to avoid
        # modifying the original array inadvertently.
        if self.transform is not None:
            img_tensor = self.transform(img_tensor)

        # Generate localisation heatmaps (peak‑normalised) for pos/neg
        loc_pos_heatmap = self.target_loc_transform(pos_pts)
        loc_neg_heatmap = self.target_loc_transform(neg_pts)

        # Generate density heatmaps (unit‑mass summed) for pos/neg
        count_pos_heatmap = self.target_count_transform(pos_pts)
        count_neg_heatmap = self.target_count_transform(neg_pts)

        loc_heatmap = torch.cat([loc_pos_heatmap, loc_neg_heatmap], dim=0)
        count_heatmap = torch.cat([count_pos_heatmap, count_neg_heatmap], dim=0)

        return img_tensor, loc_heatmap, count_heatmap, pos_pts, neg_pts


def collate_heatmap_points(batch):
    """
    Custom collation function used by the DataLoader.

    This collate function keeps the positive and negative coordinate
    lists ragged so that each image can have a variable number of
    annotations.  It stacks the images and heatmaps into dense
    tensors of shape ``(B, C, H, W)``.
    """
    imgs, loc_heatmaps, count_heatmaps, pos_points, neg_points = zip(*batch)

    imgs = torch.stack(imgs, dim=0)                # (B, 3, H, W)
    loc_heatmaps = torch.stack(loc_heatmaps, dim=0)  # (B, 2, H_out, W_out)
    count_heatmaps = torch.stack(count_heatmaps, dim=0)  # (B, 2, H_out, W_out)

    # points stay ragged: list length B, each is (Ni, 2)
    pos_points = list(pos_points)
    neg_points = list(neg_points)

    return imgs, loc_heatmaps, count_heatmaps, pos_points, neg_points